export function demoQuestions(subject, index) {
  const concepts = subject.concepts.map(([text, correct, ...wrong]) => ({
    text,
    options: [correct, ...wrong],
    correct: 0,
  }));
  const numbers = Array.from({ length: 15 }, (_, i) => {
    const base = (i + 2) * 10000 + index * 1000,
      rate = ((i % 5) + 1) * 5;
    let text, answer;
    if (index === 1) {
      const liabilities = base / 2;
      answer = base - liabilities;
      text = `В учебном балансе активы составляют ${base} ₸, обязательства — ${liabilities} ₸. Чему равен собственный капитал?`;
    } else if (index === 7) {
      const expense = base * 0.6;
      answer = base - expense;
      text = `Плановые поступления составляют ${base} ₸, выплаты — ${expense} ₸. Каков плановый чистый денежный поток?`;
    } else if (index === 9) {
      answer = rate;
      text = `Чистая прибыль составляет ${(base * rate) / 100} ₸ при выручке ${base} ₸. Какова рентабельность продаж в процентах?`;
    } else if (index === 5) {
      answer = (base * rate) / 100;
      text = `В учебном примере налоговая база равна ${base} ₸, а заданная ставка — ${rate}%. Чему равен налог? Используйте только условия задачи.`;
    } else if (index === 2) {
      answer = (base * (100 + rate)) / 100;
      text = `Цена товара составляет ${base} ₸. В учебном примере цена выросла на ${rate}%. Чему равна новая цена?`;
    } else if (index === 8) {
      answer = (base * rate) / 100;
      text = `Портфель составляет ${base} ₸. Допустимый учебный лимит потерь — ${rate}%. Какова сумма лимита в тенге?`;
    } else if (index === 6) {
      answer = (base * rate) / 100;
      text = `Выручка учебной компании равна ${base} ₸, чистая рентабельность — ${rate}%. Чему равна чистая прибыль?`;
    } else {
      answer = (base * rate) / 100;
      text = `В учебном расчёте сумма вложения составляет ${base} ₸, простая годовая ставка — ${rate}%. Чему равен доход за один год без комиссий и капитализации?`;
    }
    return {
      text,
      options: [
        String(answer),
        String(answer + Math.max(1, answer * 0.2)),
        String(answer - Math.max(1, answer * 0.1)),
        String(answer * 2),
      ],
      correct: 0,
    };
  });
  return [...concepts, ...numbers];
}
